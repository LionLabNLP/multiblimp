"""List the UD languages with NEITHER any morphological feature annotation in UD NOR any UniMorph data.

Their "% covered by UM" / "% covered by UM+UD" can only read 0%: no token carries `feats` (so the
UD-derived table is empty, see multiblimp.ud_lexicon.collect_ud_rows) and resources/unimorph has no entry.

Usage (any directory):
    python find_no_coverage_langs.py

Writes resources/langs_no_feats_no_um.txt and output/logs/find_no_coverage_langs.log.
"""
import os
import sys

_repo_root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
sys.path.append(os.path.join(_repo_root, "src"))
sys.path.append(_repo_root)

from tqdm import tqdm

from multiblimp.config import RESOURCE_DIR
from multiblimp.languages import get_ud_langs, lang2langcode
from multiblimp.script_log import script_logger
from multiblimp.treebank import Treebank


def treebank_has_feature_annotation(treebank) -> bool:
    """True if any token carries a non-empty `feats` dict (collect_ud_rows skips tokens without)."""
    for tree in treebank:
        for token in tree:
            if token.get("feats"):
                return True
    return False


def has_um_coverage(langcode: str, resource_dir: str) -> bool:
    """True if raw UniMorph data (resources/unimorph/<langcode>) exists for this language."""
    return os.path.exists(os.path.join(resource_dir, "unimorph", langcode))


def main():
    log = script_logger("find_no_coverage_langs")
    resource_dir = RESOURCE_DIR
    ud_langs = get_ud_langs(resource_dir)

    excluded = []
    for lang in tqdm(sorted(ud_langs)):
        langcode = lang2langcode(lang)

        if has_um_coverage(langcode, resource_dir):
            continue

        # selected treebanks only (excluded_treebanks applied), as in the pipeline
        treebank = Treebank(
            lang.replace(" ", "_"),
            resource_dir=resource_dir,
            load_from_pickle=True,
            remove_typo=False,
            pickle_path="ud/ud_typo_pickles",
        )
        if treebank_has_feature_annotation(treebank):
            continue

        excluded.append((lang, langcode, len(treebank)))

    out_path = os.path.join(resource_dir, "langs_no_feats_no_um.txt")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(
            "# Languages excluded from UM/UM+UD coverage stats: no token of the UD treebank has\n"
            "# feats (the UD-derived table is empty) and there is no UniMorph data either,\n"
            "# so 0% coverage is expected.\n"
            "# Generated by scripts/agreement_trees/supplementary/find_no_coverage_langs.py\n"
            "# language\tlangcode\t#sentences_scanned\n"
        )
        for lang, langcode, n_sents in excluded:
            f.write(f"{lang}\t{langcode}\t{n_sents}\n")

    log.info(f"{len(excluded)} language(s) with no UD feature annotation and no UM coverage:")
    for lang, langcode, n_sents in excluded:
        log.info(f"  {lang}\t{langcode}\t{n_sents} sentences scanned")
    log.info(f"Written to {out_path}")


if __name__ == "__main__":
    main()
